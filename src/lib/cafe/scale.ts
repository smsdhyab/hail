// قراءة باركود ميزان الأوزان (ACLAS وأمثاله — باركود «الوزن المضمّن»).
//
// الملصق يحمل EAN-13 بالبنية: بادئة «22» + رمز الصنف PLU (٥ خانات) + الوزن
// بالغرام (٥ خانات) + خانة تحقّق. فالباركود يتغيّر مع كل وزنة، لكن الـPLU
// ثابت لكل صنف — فالربط يكون بالـPLU لا بالباركود الكامل.
//
//   2 25000 40026 56  →  ليس هكذا؛ التقسيم المنطقي:
//   22 | 50004 | 00265 | 6  →  PLU 50004، الوزن 265غم = 0.265كغم
//
// البادئة «2» وحدها شائعة أيضاً في بعض الموازين؛ نقبل «2» متبوعة بأي رقم ثم
// البنية نفسها، فنجرّب «22» أولاً ثم «2x».

export type ScaleScan = { plu: number; kg: number };

/** يفكّ باركود ميزان بوزن مضمّن. يعيد null لغير المطابق (فيُعامَل كرمز آخر). */
export function parseScaleBarcode(raw: string): ScaleScan | null {
  const d = (raw ?? "").replace(/\D/g, "");
  if (d.length !== 13) return null;
  // بادئة الوزن المضمّن: 20–29 (المتجر). PLU الخانات ٢..٦، الوزن ٧..١١.
  if (d[0] !== "2") return null;
  const plu = parseInt(d.slice(2, 7), 10);
  const grams = parseInt(d.slice(7, 12), 10);
  if (!plu || grams <= 0) return null;
  return { plu, kg: grams / 1000 };
}
