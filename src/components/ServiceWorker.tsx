"use client";

import { useEffect } from "react";

/**
 * يسجّل عامل الخدمة لكل الصفحات.
 *
 * كان التسجيل داخل شريط الطاقم ومشروطاً بوجود مفتاح الإشعارات، فترتّب عليه
 * أمران: منيو الزبون لا يسجّله أصلاً — فلا يُثبَّت كتطبيق ولا يعمل بلا إنترنت —
 * وقدرة الكاشير على البيع أثناء انقطاع الإنترنت صارت معلّقة بإعداد الإشعارات،
 * فحذفه يوقف البيع بلا أن يربط أحد بين الأمرين.
 *
 * التسجيل هنا مستقل: الإشعارات تبني عليه عبر `serviceWorker.ready`.
 */
export function ServiceWorker() {
  useEffect(() => {
    if (!("serviceWorker" in navigator)) return;
    navigator.serviceWorker.register("/sw.js").catch(() => {
      /* متصفّح يمنعه، أو تصفّح خاص — الموقع يعمل بلا عامل خدمة */
    });
  }, []);
  return null;
}
