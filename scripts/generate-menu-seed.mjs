// Regenerates supabase/migrations/0022_hail_menu.sql from the HAIL catalog
// (src/lib/cafe/hail-menu.ts) so the database and the app can never disagree
// about what is on the menu. Edit the catalog, then run:
//     node scripts/generate-menu-seed.mjs
//
// Node 24 imports the .ts module directly (type stripping) — no build step.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { HAIL_MENU, STATIONS } from "../src/lib/cafe/hail-menu.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Runs AFTER 0021_stations.sql, which creates `stations` and categories.station_id.
const out = join(root, "supabase", "migrations", "0022_hail_menu.sql");

/** Single-quote a string for SQL. */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const lines = [];
lines.push(
  "-- 0022_hail_menu.sql — GENERATED by scripts/generate-menu-seed.mjs. Do not edit by",
  "-- hand; edit src/lib/cafe/hail-menu.ts and re-run the script.",
  "--",
  "-- The two cash registers and the HAIL menu transcribed from the owner's",
  "-- Adobe XD design file. Prices are IQD sell prices; cost defaults to 0 (entered",
  "-- later in «إدارة المنتجات»). Idempotent and NON-destructive: the menu is seeded",
  "-- only when empty, so admin edits are never clobbered on re-run.",
  "",
  "do $$",
  "declare",
  "  v_cat uuid;",
  "  v_item uuid;",
  "  v_station uuid;",
  "begin",
  "  -- the two registers (0021_stations.sql creates the table)",
);
for (const s of STATIONS) {
  lines.push(
    `  insert into public.stations(slug, name_ar, sort) values (${q(s.slug)}, ${q(s.name_ar)}, ${s.sort})`,
    "    on conflict (slug) do update set name_ar = excluded.name_ar, sort = excluded.sort;",
  );
}
lines.push("", "  -- seed the menu only once", "  if exists (select 1 from public.menu_items) then return; end if;", "");

HAIL_MENU.forEach((cat, ci) => {
  lines.push(
    `  -- ${cat.name_ar} → ${cat.station}`,
    `  select id into v_station from public.stations where slug = ${q(cat.station)};`,
    `  insert into public.categories(name_ar, sort, station_id) values (${q(cat.name_ar)}, ${ci + 1}, v_station) returning id into v_cat;`,
  );
  cat.items.forEach((item, ii) => {
    const active = item.active === false ? "false" : "true";
    const desc = item.description ? q(item.description) : "null";
    const flavors = item.flavors?.length ? `array[${item.flavors.map(q).join(", ")}]::text[]` : "'{}'::text[]";
    const needsId = (item.variants ?? []).length > 0;
    lines.push(
      `  insert into public.menu_items(category_id, name_ar, description_ar, price, flavors, sort, is_active)` +
        ` values (v_cat, ${q(item.name_ar)}, ${desc}, ${item.price}, ${flavors}, ${ii + 1}, ${active})` +
        (needsId ? " returning id into v_item;" : ";"),
    );
    (item.variants ?? []).forEach(([name, price], vi) => {
      lines.push(
        `  insert into public.item_variants(item_id, kind, name_ar, price_override, sort)` +
          ` values (v_item, 'size', ${q(name)}, ${price}, ${vi + 1});`,
      );
    });
  });
  lines.push("");
});

lines.push("end $$;", "");

writeFileSync(out, lines.join("\n"), "utf8");
const items = HAIL_MENU.reduce((n, c) => n + c.items.length, 0);
console.log(`✓ ${out}\n  ${STATIONS.length} stations · ${HAIL_MENU.length} categories · ${items} items`);
